"""Write the type registry of one generated ASN.1 library (plan M10).

    tools/asn1_registry.py <proto> <generated dir> <out.cpp>

asn1c's own PDU collection comes with its example program, which we do not
generate; ksim-codec and the oracle harness need to find any type by name. The
registry declares every descriptor extern (no protocol header is included, so
this stays one cheap translation unit per protocol) and lists them sorted by
name, the ASN.1 name with '-' written '_' as asn1c spells it.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PREFIX = {"rrc": "RRC", "ngap": "NGAP", "f1ap": "F1AP", "e1ap": "E1AP", "xnap": "XNAP"}
DECL = re.compile(r"^extern asn_TYPE_descriptor_t asn_DEF_(\w+);", re.M)


def main() -> int:
    proto, gen, out = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    prefix = PREFIX[proto] + "_"
    syms: set[str] = set()
    for h in sorted(gen.glob(prefix + "*.h")):
        syms.update(s for s in DECL.findall(h.read_text(errors="replace")) if s.startswith(prefix))
    if not syms:
        print(f"ASN1_REGISTRY=FAIL {proto}: no descriptors under {gen}", file=sys.stderr)
        return 1
    names = sorted((s[len(prefix):], s) for s in syms)
    lines = ["// Generated by tools/asn1_registry.py. Do not edit.",
             '#include "codec/asn1/registry.hpp"', "", 'extern "C" {']
    lines += [f"extern asn_TYPE_descriptor_t asn_DEF_{s};" for _, s in names]
    lines += ["}", "", "namespace ksim::asn1::detail {", "",
              f"extern const RegistryEntry kRegistry_{proto}[] = {{"]
    lines += [f'    {{"{n}", &asn_DEF_{s}}},' for n, s in names]
    lines += ["};", f"extern const std::size_t kRegistrySize_{proto} = {len(names)};", "",
              "} // namespace ksim::asn1::detail", ""]
    text = "\n".join(lines)
    if not out.is_file() or out.read_text() != text:   # keep the mtime when nothing changed
        out.write_text(text)
    print(f"ASN1_REGISTRY {proto} types={len(names)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
