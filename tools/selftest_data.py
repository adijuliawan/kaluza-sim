"""The data ksim-selftest carries (plan M16), generated at configure time:

    tools/selftest_data.py <out.cpp>

- the KAT files of spec/kat it checks (milenage, tuak, eea2, uea2, eia2, eia1),
  as text;
- the committed corpus (tests/vectors: NGAP, F1AP, E1AP, XnAP, RRC, NAS,
  GTP-U, PSC, NR-U) with a named type, which the M10-M12 checks showed decode
  and re-encode byte for byte; vectors their producer's test refuses and the
  undecodable ones are left out. Local-only vectors are never embedded.
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KATS = ["milenage", "tuak", "eea2", "uea2", "eia2", "eia1"]
TOP = {"ngap": "NGAP_PDU", "f1ap": "F1AP_PDU", "e1ap": "E1AP_PDU", "xnap": "XnAP_PDU"}


def rows(proto: str) -> list[dict]:
    p = ROOT / "tests" / "vectors" / proto / "index.tsv"
    if not p.is_file():
        return []
    with p.open() as f:
        return list(csv.DictReader((ln for ln in f if not ln.startswith("#")), delimiter="\t"))


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    out = Path(sys.argv[1])
    lines = ["// Generated by tools/selftest_data.py from spec/kat and tests/vectors. Do not edit.",
             '#include "selftest_data.hpp"', "", "namespace ksim::selftest {", "", "namespace {"]
    for k in KATS:
        text = (ROOT / "spec" / "kat" / f"{k}.tsv").read_text()
        assert ")KAT\"" not in text
        lines.append(f'constexpr std::string_view k_{k} = R"KAT({text})KAT";')
    lines += ["", "constexpr Vector kVectors[] = {"]
    n = 0
    for proto in ("ngap", "f1ap", "e1ap", "xnap", "rrc", "nas", "gtpu", "psc", "nru"):
        for r in rows(proto):
            pdu = r["pdu"]
            if not pdu or pdu.startswith("(") or "expects refusal" in r.get("locator", ""):
                continue
            if proto == "rrc":
                cls = pdu.split(".")[0]
                if not cls.endswith("_Message"):
                    continue
                typ = cls
            else:
                typ = TOP.get(proto, pdu)
            lines.append(f"    {{{c_str(proto)}, {c_str(typ)}, {c_str(r['id'])}, {c_str(r['hex'])}}},")
            n += 1
    lines += ["};", "", "} // namespace", "",
              "std::string_view kat(std::string_view name) {"]
    for k in KATS:
        lines.append(f'    if (name == "{k}") {{\n        return k_{k};\n    }}')
    lines += ["    return {};", "}", "",
              "std::span<const Vector> vectors() {", "    return kVectors;", "}", "",
              "} // namespace ksim::selftest", ""]
    text = "\n".join(lines)
    if not out.is_file() or out.read_text() != text:
        out.write_text(text)
    print(f"SELFTEST_DATA kats={len(KATS)} vectors={n}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
