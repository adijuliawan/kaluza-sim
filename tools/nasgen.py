"""Generate the 5GS NAS message tables (plan M11) from spec/nas/24501, with the
ePCO container identifiers of spec/nas/24008 and the GSM 7-bit alphabet of
spec/nas/23038.

    tools/nasgen.py <out.cpp>                 the C++ tables for src/codec/nas
    tools/nasgen.py --ie-types <out.tsv>       spec/nas/24501/ie_types.tsv
    tools/nasgen.py --check                    both current (CI)

Input: messages.tsv and message_ies.tsv (spec/tools/docx_tables.py, M7). Every
row of a message table becomes one IE descriptor, the header octets (EPD,
security header type, PDU session ID, PTI, message type) included: they are
the first mandatory V IEs, so one decoder serves 5GMM and 5GSM.

ie_types.tsv lists each IE type with the formats and lengths it is used with;
a type used with two different lengths for the same format fails the check.
"""

from __future__ import annotations

import csv
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAS = ROOT / "spec" / "nas" / "24501"
FORMATS = {"V": "v", "LV": "lv", "LV-E": "lv_e", "T": "t", "TV": "tv", "TLV": "tlv", "TLV-E": "tlv_e"}
PRESENCE = {"M": "m", "O": "o", "C": "c"}
def direction(text: str) -> str:
    """The table's 'Direction:' line, which TS 24.501 spells several ways
    (UE to network, UE to AMF, Network to UE, AMF to UE, both)."""
    t = text.strip().lower()
    return "ul" if t.startswith("ue to ") else "dl" if t.endswith(" to ue") else "both"


def read(name: str) -> list[dict]:
    with (NAS / name).open() as f:
        lines = [ln for ln in f if not ln.startswith("#")]
    return list(csv.DictReader(lines, delimiter="\t"))


def length(text: str) -> tuple[int, int]:
    """(min, max) total octets of an IE; a half octet is (0, 0); 'n' is unbounded (0xFFFF)."""
    t = text.replace(" ", "")
    if t == "1/2":
        return 0, 0
    m = re.fullmatch(r"(\d+)-(\d+|n)", t)
    if m:
        return int(m.group(1)), 0xFFFF if m.group(2) == "n" else min(int(m.group(2)), 0xFFFF)
    if t.isdigit():
        return int(t), int(t)
    raise ValueError(f"unreadable IE length {text!r}")


def iei(text: str) -> tuple[int, str]:
    """(IEI value, kind): kind 'none' (imperative part), 'half' (type 1: IEI in bits 8-5) or 'full'."""
    t = text.strip()
    if not t:
        return 0, "none"
    if re.fullmatch(r"[0-9A-Fa-f]-", t):
        return int(t[0], 16), "half"
    if re.fullmatch(r"[0-9A-Fa-f]{2}", t):
        return int(t, 16), "full"
    raise ValueError(f"unreadable IEI {text!r}")


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ident(key: str) -> str:
    return "k" + re.sub(r"\W", "_", key)


def tables() -> str:
    msgs = read("messages.tsv")
    ies = read("message_ies.tsv")
    by_key: dict[str, list[dict]] = {}
    for r in ies:
        by_key.setdefault(r["key"], []).append(r)
    out = ["// Generated by tools/nasgen.py from spec/nas/24501 (TS 24.501 clause 8) and",
           "// spec/nas/23038 (TS 23.038 6.2.1). Do not edit.",
           '#include <cstddef>', '#include <cstdint>', "",
           '#include "codec/nas/nas_tables.hpp"', "", "namespace ksim::nas::detail {", ""]
    entries = []
    for m in msgs:
        rows = sorted(by_key.get(m["key"], []), key=lambda r: int(r["seq"]))
        if not rows:
            continue
        out.append(f"constexpr IeDesc {ident(m['key'])}[] = {{")
        for r in rows:
            v, kind = iei(r["iei"])
            lo, hi = length(r["length"])
            out.append(f"    {{{c_str(r['ie_name'])}, {c_str(r['type_name'])}, {c_str(r['reference'])}, 0x{v:02X}, "
                       f"IeiKind::{kind}, Format::{FORMATS[r['format']]}, {lo}, {hi}, "
                       f"Presence::{PRESENCE[r['presence'][0]]}}},")
        out.append("};")
        epd = "mm" if m["protocol"] == "5GMM" else "sm"
        mtype = int(m["message_type_hex"] or "0", 16)   # 8.2.28 (security protected) has none
        entries.append(f"    {{{c_str(m['key'])}, {c_str(m['message'])}, Epd::{epd}, 0x{mtype:02X}, "
                       f"Direction::{direction(m['direction'])}, {ident(m['key'])}, "
                       f"sizeof({ident(m['key'])}) / sizeof(IeDesc)}},")
    out += ["", "extern const MsgDesc kMessages[] = {"] + entries + ["};",
            f"extern const std::size_t kMessageCount = {len(entries)};", "", "} // namespace ksim::nas::detail", ""]
    out += epco()
    out += gsm7()
    return "\n".join(out)


def epco() -> list[str]:
    """TS 24.008 10.5.6.3 container identifiers (spec/nas/24008), which the ePCO of
    TS 24.501 9.11.4.6 uses: per direction, the name and the length field size."""
    with (ROOT / "spec" / "nas" / "24008" / "epco_containers.tsv").open() as f:
        rows = list(csv.DictReader((ln for ln in f if not ln.startswith("#")), delimiter="\t"))
    dirs = {"UE-to-network": "ul", "network-to-UE": "dl"}
    out = ["// TS 24.008 10.5.6.3 container identifiers (spec/nas/24008).",
           "namespace ksim::nas::detail {", "", "extern const EpcoDesc kEpco[] = {"]
    for r in rows:
        out.append(f"    {{0x{int(r['id_hex'], 16):04X}, Direction::{dirs[r['direction']]}, {int(r['length_octets'])}, "
                   f"{c_str(r['name'])}}},")
    out += ["};", f"extern const std::size_t kEpcoCount = {len(rows)};", "", "} // namespace ksim::nas::detail", ""]
    return out


def gsm7() -> list[str]:
    """TS 23.038 6.2.1 (default alphabet) and 6.2.1.1 (extension table) as code points;
    0xFFFFFFFF marks the escape (and the extension table's reserved escape)."""
    with (ROOT / "spec" / "nas" / "23038" / "gsm7_alphabet.tsv").open() as f:
        lines = [ln for ln in f if not ln.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    default = [None] * 128
    ext = []
    for r in rows:
        cp = 0xFFFFFFFF if r["unicode"] == "ESC" else int(r["unicode"][2:], 16)
        code = int(r["code_hex"], 16)
        if r["table"] == "default":
            default[code] = cp
        elif cp != 0xFFFFFFFF:
            ext.append((code, cp))
    if any(c is None for c in default):
        raise SystemExit("NASGEN=FAIL the default alphabet is incomplete")
    out = ["// TS 23.038 GSM 7-bit default alphabet and its extension table (spec/nas/23038).",
           "namespace ksim::sms::detail {", "",
           "extern const std::uint32_t kGsm7Default[128] = {"]
    for i in range(0, 128, 8):
        out.append("    " + ", ".join(f"0x{c:04X}" if c != 0xFFFFFFFF else "0xFFFFFFFF" for c in default[i:i + 8]) + ",")
    out += ["};", "", "extern const std::uint32_t kGsm7Extension[][2] = {"]
    out += [f"    {{0x{code:02X}, 0x{cp:04X}}}," for code, cp in sorted(ext)]
    out += ["};", f"extern const std::size_t kGsm7ExtensionCount = {len(ext)};", "",
            "} // namespace ksim::sms::detail", ""]
    return out


def ie_types(rows: list[dict] | None = None) -> tuple[str, list[str]]:
    rows = read("message_ies.tsv") if rows is None else rows
    seen: dict[tuple[str, str], dict] = {}
    problems = []
    for r in rows:
        key = (r["type_name"], r["reference"])
        e = seen.setdefault(key, {"formats": {}, "messages": set()})
        lo_hi = length(r["length"])
        prev = e["formats"].setdefault(r["format"], lo_hi)
        if prev != lo_hi and r["format"] in ("V", "TV"):
            problems.append(f"{r['type_name']} ({r['reference']}) as {r['format']}: lengths {prev} and {lo_hi}")
        e["messages"].add(r["message"])
    buf = io.StringIO()
    buf.write("# IE types of TS 24.501 as the message tables use them (tools/nasgen.py). Do not edit.\n")
    w = csv.writer(buf, delimiter="\t", lineterminator="\n")
    w.writerow(["type_name", "reference", "formats", "messages"])
    for (name, ref), e in sorted(seen.items()):
        fmts = ";".join(f"{f}:{lo}-{'n' if hi == 0xFFFF else hi}" for f, (lo, hi) in sorted(e["formats"].items()))
        w.writerow([name, ref, fmts, len(e["messages"])])
    return buf.getvalue(), problems


def main() -> int:
    args = sys.argv[1:]
    if args == ["--check"]:
        text, problems = ie_types()
        cur = NAS / "ie_types.tsv"
        stale = not cur.is_file() or cur.read_text() != text
        for p in problems:
            print(f"NASGEN_PROBLEM {p}")
        print(f"NASGEN={'STALE' if stale else 'CURRENT'} problems={len(problems)}")
        tables()  # every row must be readable
        return 1 if stale or problems else 0
    if args[:1] == ["--ie-types"]:
        text, problems = ie_types()
        Path(args[1]).write_text(text)
        print(f"NASGEN ie_types={text.count(chr(10)) - 2} problems={len(problems)}")
        return 1 if problems else 0
    out = Path(args[0])
    text = tables()
    if not out.is_file() or out.read_text() != text:
        out.write_text(text)
    print(f"NASGEN messages={text.count('Direction::')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
